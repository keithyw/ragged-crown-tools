// Compares the sandbox with the real database through their two APIs. Used by
// scripts/refresh-sandbox.sh (make sandbox-refresh, ARCHITECTURE.md 6.2).
//
//   node scripts/compare-databases.mjs tile_defs items ...           report
//   node scripts/compare-databases.mjs --verify tile_defs items ...  exit 1 unless
//                                                                    the two match
//
// The report is what a refresh would do to the sandbox: documents only the
// sandbox has are lost, and a document with the same `id` but different
// content is replaced by the real one. Documents are matched by `id`, since
// `_id` is generated by each server (ARCHITECTURE.md 6.4). It is a client of
// the two APIs and never connects to MongoDB. No dependencies.

const SANDBOX_URL = process.env.SANDBOX_API_URL ?? 'http://localhost:8081'
const REAL_URL = process.env.REAL_API_URL ?? 'http://localhost:8080'

const args = process.argv.slice(2)
const verify = args.includes('--verify')
const collections = args.filter((a) => a !== '--verify')

if (collections.length === 0) {
	console.error('usage: compare-databases.mjs [--verify] <collection>...')
	process.exit(1)
}

async function fetchAll(base, collection) {
	let res
	try {
		res = await fetch(`${base}/collection/${collection}`)
	} catch {
		throw new Error(`Cannot reach the API at ${base}. Is it running?`)
	}
	if (!res.ok) {
		throw new Error(`GET ${base}/collection/${collection}: ${res.status}`)
	}
	return res.json()
}

// JSON with sorted keys, without the fields each server stamps itself, so two
// documents with the same content compare equal.
const canonical = (doc) =>
	JSON.stringify(doc, (key, value) => {
		if (key === '_id' || key === 'updated_at') return undefined
		if (value && typeof value === 'object' && !Array.isArray(value)) {
			return Object.fromEntries(
				Object.entries(value).sort(([a], [b]) => (a < b ? -1 : 1)),
			)
		}
		return value
	})

// A document with no `id` can't be matched, so it is shown by name and _id.
const label = (doc) => doc.id ?? `(no id: ${doc.name ?? doc._id})`

const rows = []
let mismatch = false

for (const collection of collections) {
	const real = await fetchAll(REAL_URL, collection)
	const sandbox = await fetchAll(SANDBOX_URL, collection)

	const realById = new Map(real.filter((d) => d.id).map((d) => [d.id, d]))
	const sandboxIds = new Set(sandbox.filter((d) => d.id).map((d) => d.id))

	const lost = sandbox.filter((d) => !d.id || !realById.has(d.id)).map(label)
	const replaced = sandbox
		.filter((d) => d.id && realById.has(d.id))
		.filter((d) => canonical(d) !== canonical(realById.get(d.id)))
		.map(label)
	const added = real.filter((d) => !d.id || !sandboxIds.has(d.id)).length

	rows.push({ collection, real, sandbox, lost, replaced, added })

	// After a refresh the two must be the same set of documents, `_id` included.
	const realIds = new Set(real.map((d) => d._id))
	if (
		real.length !== sandbox.length ||
		sandbox.some((d) => !realIds.has(d._id))
	) {
		mismatch = true
	}
}

if (verify) {
	for (const r of rows) {
		const ok = r.real.length === r.sandbox.length
		console.log(
			`${ok ? 'ok     ' : 'DIFFERS'} ${r.collection.padEnd(10)} real ${r.real.length}, sandbox ${r.sandbox.length}`,
		)
	}
	if (mismatch) {
		console.error('The sandbox does not match the real database.')
		process.exit(1)
	}
	process.exit(0)
}

console.log(`real ${REAL_URL}   sandbox ${SANDBOX_URL}\n`)
for (const r of rows) {
	console.log(
		`${r.collection.padEnd(10)} real ${String(r.real.length).padStart(3)}   sandbox ${String(r.sandbox.length).padStart(3)}   will be added ${r.added}`,
	)
	if (r.lost.length > 0) {
		console.log(`    only in the sandbox (lost): ${r.lost.join(', ')}`)
	}
	if (r.replaced.length > 0) {
		console.log(`    same id, sandbox copy replaced: ${r.replaced.join(', ')}`)
	}
}
